export function translateText(value: string, language: Language): string {
  const leading = value.match(/^\s*/)?.[0] ?? '';
  const trailing = value.match(/\s*$/)?.[0] ?? '';
  const text = value.trim();
  const translated = polishedCopy[text]?.[language]
    || polishedPatterns
      .map(([pattern, translate]) => {
        const match = text.match(pattern);
        return match ? translate(match, language) : null;
      })
      .find(Boolean)
    || (language === 'fr' ? text : english[text]
      || patterns.map(([pattern, translate]) => text.match(pattern) && translate(text.match(pattern)!)).find(Boolean)
      || text);
  return `${leading}${translated}${trailing}`;
}

export function getStoredLanguage(): Language {
  try {
    const stored = localStorage.getItem(LANGUAGE_STORAGE_KEY);
    return stored === 'en' || stored === 'fr' ? stored : DEFAULT_LANGUAGE;
  } catch {
    return DEFAULT_LANGUAGE;
  }
}
